const fs = require("node:fs"),
  path = require("node:path"),
  ts = require("typescript"),
  zlib = require("node:zlib");
const root = path.resolve(__dirname, ".."),
  out = path.join(root, ".cloudflare");
fs.mkdirSync(out, { recursive: true });
function bundle(entry, browser) {
  const modules = [],
    ids = new Map(),
    external = new Map();
  const aliases = browser
    ? {}
    : {
        [path.join(root, "lib/db.ts")]: path.join(root, "cloudflare/db.ts"),
        [path.join(root, "lib/security.ts")]: path.join(
          root,
          "cloudflare/security.ts",
        ),
      };
  const packages = {
    react: "react/cjs/react.production.js",
    "react/jsx-runtime": "react/cjs/react-jsx-runtime.production.js",
    "react-dom/client": "react-dom/cjs/react-dom-client.production.js",
    "react-dom": "react-dom/cjs/react-dom.production.js",
    scheduler: "scheduler/cjs/scheduler.production.js",
  };
  function add(file) {
    file = aliases[file] || file;
    if (ids.has(file)) return ids.get(file);
    const id = modules.length;
    ids.set(file, id);
    modules.push(null);
    const source = fs.readFileSync(file, "utf8"),
      code = /\.[cm]?js$/.test(file)
        ? source
        : ts.transpileModule(source, {
            compilerOptions: {
              target: ts.ScriptTarget.ES2022,
              module: ts.ModuleKind.CommonJS,
              jsx: ts.JsxEmit.ReactJSX,
              esModuleInterop: true,
            },
            fileName: file,
          }).outputText;
    const deps = {};
    for (const match of code.matchAll(/\brequire\(["']([^"']+)["']\)/g)) {
      const name = match[1];
      if (name.startsWith("node:") || name === "cloudflare:workers") {
        if (browser) throw Error("Node import reached browser: " + name);
        if (!external.has(name)) external.set(name, "external" + external.size);
        deps[name] = name;
        continue;
      }
      let target;
      if (name.startsWith(".")) {
        const p = path.resolve(path.dirname(file), name);
        target = [
          p,
          p + ".ts",
          p + ".tsx",
          p + ".js",
          path.join(p, "index.ts"),
        ].find((p) => fs.existsSync(p) && fs.statSync(p).isFile());
      } else if (packages[name])
        target = path.join(root, "node_modules", packages[name]);
      else throw Error("Unmapped package " + name + " from " + file);
      if (!target) throw Error("Missing module " + name + " from " + file);
      deps[name] = add(target);
    }
    modules[id] =
      `[function(require,module,exports){\n${code}\n},${JSON.stringify(deps)}]`;
    return id;
  }
  const id = add(path.join(root, entry));
  const imports = [...external]
    .map(
      ([name, varname]) =>
        `import * as ${varname} from ${JSON.stringify(name)};`,
    )
    .join("\n");
  const pre = browser
    ? 'const process={env:{NODE_ENV:"production"}};'
    : `import {Buffer} from 'node:buffer';`;
  const externals =
    "{" +
    [...external].map(([n, v]) => JSON.stringify(n) + ":" + v).join(",") +
    "}";
  const runtime = `${pre}\nconst modules=[${modules.join(",\n")}],cache={},externals=${externals};function load(id){if(typeof id==='string')return externals[id];if(cache[id])return cache[id].exports;const module=cache[id]={exports:{}};const [fn,deps]=modules[id];fn(name=>{if(!(name in deps))throw Error('Unresolved module '+name);return load(deps[name]);},module,module.exports);return module.exports;}\nconst entry=load(${id});`;
  return (
    imports +
    "\n" +
    (browser
      ? "(()=>{" + runtime + "})();"
      : runtime +
        "\nexport const VyralStudio=entry.VyralStudio;export default entry.default;")
  );
}
const client = bundle("cloudflare/client.tsx", true),
  css = fs.readFileSync(path.join(root, "app/globals.css"), "utf8") + "\n" +
    fs.readFileSync(path.join(root, "vendor/nordify/liquid-glass.css"), "utf8");
const assetVersion = require("node:crypto")
  .createHash("sha256")
  .update(client + css)
  .digest("hex")
  .slice(0, 16);
fs.writeFileSync(
  path.join(root, "cloudflare/assets.ts"),
  "// Generated by scripts/build-cloudflare.cjs; do not commit.\nexport const assetVersion=" +
    JSON.stringify(assetVersion) +
    ";\nexport const client=" +
    JSON.stringify(client) +
    ";\nexport const css=" +
    JSON.stringify(css) +
    ";\n",
);
const worker = bundle("cloudflare/server.ts", false);
fs.writeFileSync(path.join(out, "worker.js"), worker);
fs.writeFileSync(path.join(out, "client.js"), client);
console.log(
  JSON.stringify({
    clientBytes: Buffer.byteLength(client),
    workerBytes: Buffer.byteLength(worker),
    workerGzipBytes: zlib.gzipSync(worker).length,
  }),
);

